"""Generate Markdown docs from the built warehouse, so documentation always matches the data.

  docs/data_dictionary.md  star schema tables and columns, from COMMENT ON metadata in sql/40_marts
  docs/data_quality.md     raw-file profile and the % of rows failing each test
  docs/results.md          headline metrics from the rpt.* tables

Usage:  .venv\\Scripts\\python.exe -I pipeline\\docs.py
"""
from __future__ import annotations

import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "data" / "hcareledger.duckdb"
DOCS = ROOT / "docs"

STAR_ORDER = [
    "fct_claim_line", "fct_drug_event", "fct_member_month", "fct_inpatient_stay",
    "dim_beneficiary_year", "dim_provider", "dim_diagnosis", "dim_date", "dim_service_type",
]
GRAIN = {
    "fct_claim_line": "one row per medical claim line",
    "fct_drug_event": "one row per Part D drug event",
    "fct_member_month": "one row per beneficiary per enrolled month",
    "fct_inpatient_stay": "one row per merged acute inpatient stay",
    "dim_beneficiary_year": "one row per beneficiary per year",
    "dim_provider": "one row per NPI or CCN",
    "dim_diagnosis": "one row per ICD-10-CM code on claims",
    "dim_date": "one row per day",
    "dim_service_type": "one row per benefit category",
}
# Relationships are defined once, in the Power BI model generator.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from powerbi import RELATIONSHIPS as PBI_RELATIONSHIPS  # noqa: E402

RELATIONSHIPS = [(ft, fc, tt, tc + ("" if active else " (inactive role)")) for ft, fc, tt, tc, active in PBI_RELATIONSHIPS]


def md_table(headers: list[str], rows: list[tuple], align: str | None = None) -> str:
    """Render rows as a Markdown table. Pass years as strings so they are not comma-formatted."""
    def fmt(v):
        if v is None:
            return ""
        if isinstance(v, bool):
            return "yes" if v else "no"
        if isinstance(v, (float, Decimal)):
            return f"{v:,.0f}" if float(v).is_integer() and abs(v) >= 1000 else f"{v:,.2f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|")
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(align or ["---"] * len(headers)) + " |"]
    out += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def data_dictionary(con: duckdb.DuckDBPyConnection) -> str:
    parts = [
        "# Data dictionary",
        "",
        f"_Generated by `pipeline/docs.py` from the `COMMENT ON` metadata in `sql/40_marts/` on {date.today():%Y-%m-%d}._",
        "",
        "Star schema in the `mart` schema of `data/hcareledger.duckdb`, exported to `outputs/powerbi/*.parquet`.",
        "Every dimension except `dim_date` has an unknown member with key `-1`; facts never carry a NULL foreign key.",
        "",
        "## Relationships",
        "",
        md_table(["Fact", "Foreign key", "Dimension", "Key"], RELATIONSHIPS),
        "",
        "## Tables",
        "",
        md_table(
            ["Table", "Grain", "Rows"],
            [(f"[`{t}`](#{t})", GRAIN[t], con.execute(f"select count(*) from mart.{t}").fetchone()[0]) for t in STAR_ORDER],
        ),
    ]
    for t in STAR_ORDER:
        comment = con.execute(
            "select comment from duckdb_tables() where schema_name = 'mart' and table_name = ?", [t]
        ).fetchone()[0]
        cols = con.execute(
            "select column_name, data_type, coalesce(comment, '') from duckdb_columns() "
            "where schema_name = 'mart' and table_name = ? order by column_index", [t]
        ).fetchall()
        parts += ["", f"### {t}", "", comment or "", "", f"Grain: {GRAIN[t]}.", "", md_table(["Column", "Type", "Description"], cols)]
    return "\n".join(parts) + "\n"


def data_quality(con: duckdb.DuckDBPyConnection) -> str:
    tables = con.execute(
        "select table_name, grain, column_count, row_count, distinct_ids, duplicate_grain_rows, distinct_benes, "
        "min_service_date, max_service_date from audit.profile_tables order by row_count desc"
    ).fetchall()
    checks = con.execute(
        "select category, table_name, check_name, rows_checked, rows_flagged, pct_flagged from audit.profile_checks "
        "where rows_flagged > 0 order by category, pct_flagged desc"
    ).fetchall()
    n_checks, n_clean = con.execute("select count(*), count(*) filter (where rows_flagged = 0) from audit.profile_checks").fetchone()
    tests = con.execute(
        "select test_id, test_type, model, column_name, severity, description, rows_tested, rows_failing, pct_failing, status "
        "from audit.test_results order by test_id"
    ).fetchall()
    n_err = sum(1 for t in tests if t[4] == "error")
    n_err_pass = sum(1 for t in tests if t[4] == "error" and t[9] == "pass")
    n_warn = sum(1 for t in tests if t[9] == "warn")
    return "\n".join([
        "# Data quality",
        "",
        f"_Generated by `pipeline/docs.py` on {date.today():%Y-%m-%d}._",
        "",
        "## 1. Raw file profile",
        "",
        "Row counts and keys for each CMS file as delivered (`audit.profile_tables`). "
        "Per-column null %, cardinality and min/max for all columns are in `outputs/quality/profile_columns.csv`.",
        "",
        md_table(["File", "Grain", "Columns", "Rows", "Distinct IDs", "Duplicate grain rows", "Beneficiaries", "First date", "Last date"], tables),
        "",
        "## 2. Profiling checks that flagged rows",
        "",
        f"{n_checks} checks ran across duplicates, nulls, impossible dates, referential integrity and internal consistency "
        f"(`audit.profile_checks`); {n_clean} found nothing. The {n_checks - n_clean} that flagged rows:",
        "",
        md_table(["Category", "File", "Check", "Rows checked", "Rows flagged", "% flagged"], checks),
        "",
        "How each finding is handled:",
        "",
        "- **Institutional line payments don't reconcile** (outpatient, HHA, hospice; inpatient/SNF have no line payment): "
        "the claim header payment is authoritative and is placed on the first line. A reconciliation test proves per-claim totals match CMS.",
        "- **Annual Part B / Part D / dual month totals disagree with monthly fields**: eligibility is always derived from the monthly fields, "
        "which line up with the claims (no carrier claims fall in Part-A-only months).",
        "- **Enrollment years after March 2023**: the 2024-2025 files have no claims to match; they sit outside the reporting window.",
        "- **DME claims whose line dates differ by a day**: claim dates are normalised to the claim-wide min/max so each claim has one incurred month.",
        "- **No death dates**: mortality-based exclusions (e.g. readmission index stays ending in death) cannot be applied; noted as a limitation.",
        "",
        "## 3. Tests on the star schema",
        "",
        f"{len(tests)} tests (`sql/50_tests/tests.sql`, results in `audit.test_results`). "
        f"**{n_err_pass} of {n_err} error-severity tests pass**; {n_warn} warning tests quantify known data conditions.",
        "",
        md_table(["#", "Type", "Model", "Column", "Severity", "Description", "Rows tested", "Rows failing", "% failing", "Status"], tests),
        "",
    ])


def results(con: duckdb.DuckDBPyConnection) -> str:
    q = lambda sql: con.execute(sql).fetchall()
    kpi = q("select metric, period, value, unit from rpt.kpi_summary order by sort_order")
    pmpm = q("""
        select year::varchar, * exclude (year) from (
            pivot (select year, service_type, pmpm from rpt.pmpm_yearly)
            on service_type in ('Inpatient', 'Outpatient', 'Professional', 'SNF', 'Hospice', 'Home Health', 'DME', 'Total Medical', 'Part D')
            using first(pmpm)
        ) order by year""")
    util = q("select year::varchar, member_months, admissions, admissions_per_1000, average_length_of_stay, paid_per_admission, "
             "outpatient_visits_per_1000, professional_claims_per_1000 from rpt.utilization_yearly order by year")
    readm = q("select period, index_stays, readmissions_30d, readmission_rate_pct, unplanned_readmissions_30d, "
              "unplanned_readmission_rate_pct from rpt.readmission_yearly")
    dx = q("select cost_rank, category_code, category_description, paid_amount, pct_of_medical_paid, claim_count, members "
           "from rpt.top_diagnosis_categories where cost_rank <= 10 order by cost_rank")
    rx = q("select year::varchar, average_enrolled_members, fills, plan_paid, plan_paid_pmpm, plan_paid_per_member_per_year, "
           "gross_cost_per_member_per_year, generic_dispensing_rate_pct from rpt.partd_yearly order by year")
    conc = q("select period, members, total_paid, top_1pct_share, top_5pct_share, top_10pct_share, top_20pct_share, "
             "bottom_50pct_share, is_partial_or_pooled from rpt.cost_concentration order by year nulls last")
    return "\n".join([
        "# Results",
        "",
        f"_Generated by `pipeline/docs.py` on {date.today():%Y-%m-%d}._",
        "",
        "> **Synthetic data.** CMS states the synthetic files' payment amounts and utilization do not match real Medicare. "
        "These numbers demonstrate the method only; they are not facts about Medicare. Several artifacts are obvious "
        "(e.g. a pregnancy-supervision code is the #2 cost category, 78% of inpatient claims have zero utilization days, "
        "30-day readmission is about double typical Medicare rates).",
        "",
        "Reporting window: March 2015 - February 2023 (complete months of claims). 2015 has 10 months and 2023 has 2.",
        "",
        "## Headline measures",
        "",
        md_table(["Metric", "Period", "Value", "Unit"], kpi),
        "",
        "## PMPM by year and service type",
        "",
        "Medical PMPM = Medicare paid / medical member months (Part A + B, no HMO). Part D PMPM = plan paid / Part D member months.",
        "",
        md_table(["Year", "Inpatient", "Outpatient", "Professional", "SNF", "Hospice", "Home Health", "DME", "Total Medical", "Part D"], pmpm),
        "",
        "## Utilization",
        "",
        md_table(["Year", "Member months", "Admissions", "Admits / 1,000", "ALOS", "Paid / admission", "OP visits / 1,000", "Prof. claims / 1,000"], util),
        "",
        "## 30-day readmissions",
        "",
        "Index stays: acute stays (overlapping and same-day-transfer claims merged) discharged alive, not transferred, "
        "with a full 30-day follow-up inside the window. Unplanned excludes elective (type 3) readmissions as a planned proxy.",
        "",
        md_table(["Period", "Index stays", "Readmissions", "Rate %", "Unplanned", "Unplanned rate %"], readm),
        "",
        "## Top diagnosis categories by cost",
        "",
        "Medical paid attributed to the claim's principal diagnosis, full window.",
        "",
        md_table(["Rank", "Category", "Description", "Paid", "% of medical paid", "Claims", "Members"], dx),
        "",
        "## Part D spend per member",
        "",
        "Per member per year = plan paid / (Part D member months / 12).",
        "",
        md_table(["Year", "Avg enrolled", "Fills", "Plan paid", "Plan paid PMPM", "Plan paid PMPY", "Gross cost PMPY", "Generic %"], rx),
        "",
        "## Cost concentration",
        "",
        "Share of total spend (medical paid + Part D plan paid) from the costliest members. Population includes zero-spend members. "
        "Compare complete years only (`partial/pooled` = true for 2015, 2023 and the pooled all-years row).",
        "",
        md_table(["Period", "Members", "Total paid", "Top 1 %", "Top 5 %", "Top 10 %", "Top 20 %", "Bottom 50 %", "Partial/pooled"], conc),
        "",
    ])


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    con = duckdb.connect(str(DB_PATH), read_only=True)
    for name, fn in [("data_dictionary.md", data_dictionary), ("data_quality.md", data_quality), ("results.md", results)]:
        (DOCS / name).write_text(fn(con), encoding="utf-8", newline="\n")
        print(f"wrote docs/{name}")
    con.close()


if __name__ == "__main__":
    main()
